import fs from 'node:fs';
import path from 'node:path';
import {
  measureFrame,
  projectRoot,
  readManifest,
  readPng,
  summarizeGroup,
} from './character-sheet-tools.mjs';

const strict = process.argv.includes('--strict');
const manifest = readManifest();
const report = {
  generatedAt: new Date().toISOString(),
  manifestVersion: manifest.version,
  thresholds: manifest.thresholds,
  sheets: [],
};

for (const sheet of manifest.sheets) {
  const png = readPng(sheet.runtime);
  const sourcePng = readPng(sheet.source);
  const expectedWidth = sheet.frameWidth * sheet.columns;
  const expectedHeight = sheet.frameHeight * sheet.rows;
  const dimensionFailure = png.width === expectedWidth && png.height === expectedHeight
    ? null
    : `expected ${expectedWidth}x${expectedHeight}, got ${png.width}x${png.height}`;
  const groups = Object.entries(sheet.groups).map(([groupName, frameIndexes]) => {
    const frames = frameIndexes.map((frameIndex) => (
      measureFrame(png, sheet, frameIndex, manifest.thresholds.alpha)
    ));
    return {
      ...summarizeGroup(groupName, frames, manifest.thresholds),
      frames: frames.map(({ palette, ...frame }) => frame),
    };
  });
  const baselineGroups = Object.entries(sheet.groups).map(([groupName, frameIndexes]) => {
    const frames = frameIndexes.map((frameIndex) => (
      measureFrame(sourcePng, sheet, frameIndex, manifest.thresholds.alpha)
    ));
    return summarizeGroup(groupName, frames, manifest.thresholds);
  });
  const allFrames = Array.from({ length: sheet.columns * sheet.rows }, (_, frameIndex) => (
    measureFrame(png, sheet, frameIndex, manifest.thresholds.alpha)
  ));
  const allowedEmptyFrames = new Set(sheet.allowEmptyFrames ?? []);
  const unexpectedEmptyFrames = allFrames
    .filter((frame) => frame.empty && !allowedEmptyFrames.has(frame.frameIndex))
    .map((frame) => frame.frameIndex);
  const edgeFrames = allFrames
    .filter((frame) => frame.edgePixelCount > 0)
    .map((frame) => ({ frameIndex: frame.frameIndex, edgePixelCount: frame.edgePixelCount }));
  const hardFailures = [
    ...(dimensionFailure ? [dimensionFailure] : []),
    ...(unexpectedEmptyFrames.length > 0 ? [`unexpected empty frames: ${unexpectedEmptyFrames.join(', ')}`] : []),
    ...(edgeFrames.length > 0 ? [`visible edge pixels in frames: ${edgeFrames.map((frame) => `${frame.frameIndex} (${frame.edgePixelCount})`).join(', ')}`] : []),
    ...groups.flatMap((group) => group.hardFailures.map((failure) => `${group.name}: ${failure}`)),
  ];
  report.sheets.push({
    id: sheet.id,
    label: sheet.label,
    runtime: sheet.runtime,
    dimensions: { width: png.width, height: png.height },
    allFrameGate: {
      checkedFrames: allFrames.length,
      allowedEmptyFrames: [...allowedEmptyFrames],
      unexpectedEmptyFrames,
      edgeFrames,
    },
    baselineGroups,
    groups,
    hardFailures,
    passed: hardFailures.length === 0,
  });
}

const jsonPath = path.join(projectRoot, 'docs', 'qa', 'character-assets-latest.json');
const markdownPath = path.join(projectRoot, 'docs', 'qa', 'character-assets-latest.md');
fs.mkdirSync(path.dirname(jsonPath), { recursive: true });
fs.writeFileSync(jsonPath, `${JSON.stringify(report, null, 2)}\n`);
fs.writeFileSync(markdownPath, createMarkdown(report));

const failedSheets = report.sheets.filter((sheet) => !sheet.passed);
console.log(`Character asset QA: ${report.sheets.length - failedSheets.length}/${report.sheets.length} sheets pass hard gates.`);
console.log(`Report: ${path.relative(projectRoot, markdownPath)}`);
for (const sheet of failedSheets) {
  console.error(`${sheet.label}: ${sheet.hardFailures.join('; ')}`);
}
if (strict && failedSheets.length > 0) {
  process.exitCode = 1;
}

function createMarkdown(result) {
  const lines = [
    '# Character Asset QA — Latest',
    '',
    `Generated: ${result.generatedAt}`,
    '',
    '> This report is generated by `npm run assets:qa`. Position gates are hard failures; height and palette metrics are review warnings because pose and embedded action FX can change the visible silhouette intentionally.',
    '',
    '| Sheet | Group | Foot drift before -> after | Root drift before -> after | Height delta | Palette distance | Edge pixels | Result |',
    '|---|---|---:|---:|---:|---:|---:|---|',
  ];
  for (const sheet of result.sheets) {
    for (const group of sheet.groups) {
      const baseline = sheet.baselineGroups.find((candidate) => candidate.name === group.name);
      const warning = group.warnings.length > 0 ? ` ⚠ ${group.warnings.join('; ')}` : '';
      lines.push(`| ${sheet.label} | ${group.name} | ${baseline?.footLineDriftPx ?? '-'}px -> ${group.footLineDriftPx}px | ${baseline?.rootAnchorDriftPx ?? '-'}px -> ${group.rootAnchorDriftPx}px | ${group.heightDeltaPercent}% | ${group.paletteDistance} | ${group.edgePixelCount} | ${group.passed ? 'PASS' : 'FAIL'}${warning} |`);
    }
  }
  lines.push('', '## Hard failures', '');
  const failures = result.sheets.flatMap((sheet) => sheet.hardFailures.map((failure) => `- **${sheet.label}:** ${failure}`));
  lines.push(...(failures.length > 0 ? failures : ['- None.']));
  lines.push('', '## Whole-sheet gate', '');
  for (const sheet of result.sheets) {
    const gate = sheet.allFrameGate;
    lines.push(`- **${sheet.label}:** ${gate.checkedFrames} cells checked; ${gate.edgeFrames.length} edge-clipped frames; ${gate.unexpectedEmptyFrames.length} unexpected empty frames.`);
  }
  lines.push('', '## Interpretation', '');
  lines.push('- Foot-line drift uses the lowest opaque body pixel; root/core drift uses a dense-body proxy that ignores most long weapon extents.');
  lines.push('- The inferred root is a deterministic QA proxy. A future source-art pipeline should export an explicit foot/root marker per frame.');
  lines.push('- Palette distance compares saturated-color hue histograms. It flags suspicious changes but still requires a human costume/material review.');
  lines.push('- Zero edge pixels is enforced across every sheet cell, not only Idle and Walk.');
  return `${lines.join('\n')}\n`;
}
